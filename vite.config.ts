/// <reference types="vitest" />
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { defineConfig, type Plugin } from 'vitest/config';
import react from '@vitejs/plugin-react';
import { MONETIZATION } from './src/config/monetization';

/**
 * Public URL of the site, used for canonical links, Open Graph, the sitemap and
 * the share text. Netlify sets URL automatically; elsewhere set SITE_URL.
 */
const SITE_URL = (process.env.SITE_URL || process.env.URL || 'http://localhost:4173').replace(/\/$/, '');
process.env.VITE_SITE_URL = SITE_URL;

const PAGES = ['/', '/rreth/', '/privatesia/'];

function adsOn() {
  return MONETIZATION.ads.enabled && MONETIZATION.ads.publisherId.startsWith('ca-pub-');
}

function contentSecurityPolicy(): string {
  const script = ["'self'"];
  const connect = ["'self'"];
  const frame: string[] = [];
  if (adsOn()) {
    const google = [
      'https://pagead2.googlesyndication.com',
      'https://*.googlesyndication.com',
      'https://*.doubleclick.net',
      'https://*.google.com',
      'https://*.gstatic.com',
      'https://*.adtrafficquality.google',
      'https://fundingchoicesmessages.google.com',
    ];
    script.push(...google);
    connect.push(...google);
    frame.push('https://*.doubleclick.net', 'https://*.googlesyndication.com', 'https://*.google.com', 'https://*.adtrafficquality.google');
  }
  const a = MONETIZATION.analytics;
  if (a.provider === 'goatcounter') {
    script.push('https://gc.zgo.at');
    connect.push('https://*.goatcounter.com');
  } else if (a.provider === 'cloudflare') {
    script.push('https://static.cloudflareinsights.com');
    connect.push('https://cloudflareinsights.com');
  } else if (a.provider === 'plausible') {
    const origin = new URL(a.plausibleScriptUrl).origin;
    script.push(origin);
    connect.push(origin);
  }
  return [
    "default-src 'self'",
    `script-src ${script.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: https:",
    "font-src 'self'",
    `connect-src ${connect.join(' ')}`,
    `frame-src ${frame.length ? frame.join(' ') : "'none'"}`,
    "worker-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
}

/** Netlify and Cloudflare Pages both read _headers from the publish directory. */
function headersFile(): string {
  return `# Generated by vite.config.ts at build time. Netlify and Cloudflare Pages read this file.
/*
  Content-Security-Policy: ${contentSecurityPolicy()}
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin-allow-popups

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/icons/*
  Cache-Control: public, max-age=604800

/sw.js
  Cache-Control: no-cache

/manifest.webmanifest
  Cache-Control: public, max-age=86400

/*.html
  Cache-Control: public, max-age=0, must-revalidate
`;
}

function serviceWorker(files: string[], version: string): string {
  return `// Generated at build time by vite.config.ts.
const CACHE = 'fjaleza-${version}';
const PRECACHE = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('fjaleza-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  const url = new URL(req.url);
  // Ads, analytics and anything cross-origin always go straight to the network.
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    // Network first so a new release shows up, cached page when offline.
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        })
        .catch(() => caches.match(req).then((r) => r || caches.match('/index.html')))
    );
    return;
  }

  // Hashed assets never change: cache first.
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && url.pathname.startsWith('/assets/')) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
    )
  );
});
`;
}

function staticSite(): Plugin {
  return {
    name: 'fjaleza-static-site',
    apply: 'build',
    generateBundle(_options, bundle) {
      if (SITE_URL.startsWith('http://localhost')) {
        this.warn('SITE_URL is not set: canonical and Open Graph URLs point to localhost. Set SITE_URL for production builds.');
      }
      const emit = (fileName: string, source: string) => this.emitFile({ type: 'asset', fileName, source });

      const files = Object.keys(bundle)
        .filter((f) => /\.(js|css|woff2|html)$/.test(f))
        .map((f) => (f === 'index.html' ? '/' : `/${f.replace(/index\.html$/, '')}`));
      const staticFiles = ['/manifest.webmanifest', '/icons/icon-192.png', '/icons/icon-512.png', '/favicon.svg', '/theme-init.js'];
      const precache = [...new Set([...files, ...staticFiles])].sort();
      const version = createHash('sha256').update(precache.join('|')).digest('hex').slice(0, 10);
      emit('sw.js', serviceWorker(precache, version));

      emit('_headers', headersFile());

      const today = new Date().toISOString().slice(0, 10);
      emit(
        'sitemap.xml',
        `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${PAGES.map(
          (p) => `  <url><loc>${SITE_URL}${p}</loc><lastmod>${today}</lastmod></url>`
        ).join('\n')}\n</urlset>\n`
      );
      emit('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);

      const pub = MONETIZATION.ads.publisherId.replace(/^ca-/, '');
      emit(
        'ads.txt',
        pub.startsWith('pub-')
          ? `google.com, ${pub}, DIRECT, f08c47fec0942fa0\n`
          : '# Authorised digital sellers for this site.\n# Generated from src/config/monetization.ts: set ads.publisherId to fill this in.\n'
      );
    },
  };
}

