#!/usr/bin/env node
/**
 * Validate words/answers.txt and words/guesses.txt, then compile them into
 * src/data/generated/ for the app. Runs automatically before dev, build and test.
 *
 * Checks (the build fails if any is violated):
 *   - every word is exactly 5 characters from the Albanian alphabet, lowercase NFC
 *   - no duplicates in either list
 *   - every answer is also a valid guess
 *   - no offensive word in either list, no sensitive or function word in answers
 *
 * The answer schedule is obfuscated (XOR + base64) so tomorrow's word is not
 * readable as plain text in the shipped JavaScript. This is not security, it only
 * keeps the answer from being spotted by accident when viewing the source.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isAlbanianAlphabetic } from './lib/sources.mjs';
import { FUNCTION_WORDS, SENSITIVE, isOffensive } from './lib/exclusions.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LENGTH = 5;

function read(file) {
  return readFileSync(join(root, 'words', file), 'utf8')
    .split(/\r?\n/)
    .map((l) => l.replace(/#.*/, '').trim())
    .filter(Boolean);
}

const answers = read('answers.txt');
const guesses = read('guesses.txt');
const errors = [];

function check(list, name) {
  const seen = new Set();
  for (const w of list) {
    if (w !== w.normalize('NFC').toLocaleLowerCase('sq')) errors.push(`${name}: "${w}" is not lowercase NFC`);
    if ([...w].length !== LENGTH) errors.push(`${name}: "${w}" has ${[...w].length} characters`);
    if (!isAlbanianAlphabetic(w)) errors.push(`${name}: "${w}" has characters outside the Albanian alphabet`);
    if (seen.has(w)) errors.push(`${name}: duplicate "${w}"`);
    if (isOffensive(w)) errors.push(`${name}: offensive word "${w}"`);
    seen.add(w);
  }
  return seen;
}

const guessSet = check(guesses, 'guesses.txt');
check(answers, 'answers.txt');
for (const w of answers) {
  if (!guessSet.has(w)) errors.push(`answers.txt: "${w}" is not in guesses.txt`);
  if (FUNCTION_WORDS.has(w) || SENSITIVE.has(w)) errors.push(`answers.txt: "${w}" is a function or sensitive word`);
}

if (errors.length) {
  console.error(`Word list validation failed (${errors.length} problems):\n  ${errors.slice(0, 50).join('\n  ')}`);
  process.exit(1);
}

// Must match decodeAnswer() in src/game/words.ts.
function encode(word, index) {
  const bytes = Buffer.from(word, 'utf8');
  for (let j = 0; j < bytes.length; j++) bytes[j] ^= (index * 31 + j * 7 + 13) & 0xff;
  return bytes.toString('base64').replace(/=+$/, '');
}

const outDir = join(root, 'src', 'data', 'generated');
mkdirSync(outDir, { recursive: true });
const banner = '// Generated by scripts/compile-words.mjs from words/*.txt. Do not edit by hand.\n';
writeFileSync(
  join(outDir, 'answers.ts'),
  `${banner}export const ENCODED_ANSWERS: readonly string[] = ${JSON.stringify(answers.map(encode))};\n`
);
writeFileSync(
  join(outDir, 'guesses.ts'),
  `${banner}// Loaded lazily with import(). Space separated to keep the chunk small.\nexport default ${JSON.stringify(guesses.join(' '))};\n`
);
console.log(`Word lists OK: ${answers.length} answers, ${guesses.length} valid guesses.`);
